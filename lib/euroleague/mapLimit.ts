/**
 * Kao Promise.all(items.map(fn)), ali najviše `limit` zahteva istovremeno.
 * Da ne pošaljemo stotinu zahteva EuroLeague API-ju u istoj milisekundi.
 */
export async function mapLimit<T, R>(
  items: T[],
  limit: number,
  fn: (item: T) => Promise<R>,
): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      results[i] = await fn(items[i]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}
